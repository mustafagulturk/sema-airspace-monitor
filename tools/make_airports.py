#!/usr/bin/env python3
"""Generate data/airports_tr.json from the OurAirports airports.csv (public domain).

Kept: Turkish airports (iso_country TR) of type large_airport or medium_airport
with scheduled passenger service. Dropped on purpose: anything OurAirports names
or tags as an air base / army field, so the statistics never describe military
airfields (see "Etik ve hukuki sınırlar" in README). Civil terminals of joint-use
airports stay in; military aircraft are removed from the data before any
statistics are computed, so only civil movements are ever counted there.

Usage:
  curl -LO https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/airports.csv
  python3 tools/make_airports.py airports.csv data/airports_tr.json
"""
import csv
import json
import re
import sys

MILITARY = re.compile(r"air\s*base|airbase|army|military|hava üssü", re.IGNORECASE)
FT = 0.3048


def main(src: str, dst: str) -> None:
    out = []
    with open(src, encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            if row["iso_country"] != "TR":
                continue
            if row["type"] not in ("large_airport", "medium_airport"):
                continue
            if row["scheduled_service"] != "yes":
                continue
            if MILITARY.search(row["name"]) or MILITARY.search(row["keywords"]):
                continue
            icao = row["gps_code"] or row["ident"]
            if not re.fullmatch(r"LT[A-Z]{2}", icao):
                continue
            elev = row["elevation_ft"]
            out.append(
                {
                    "icao": icao,
                    "iata": row["iata_code"],
                    "name": row["name"],
                    "city": row["municipality"],
                    "lat": round(float(row["latitude_deg"]), 5),
                    "lon": round(float(row["longitude_deg"]), 5),
                    "elevation_m": round(float(elev) * FT) if elev else 0,
                    "large": row["type"] == "large_airport",
                }
            )
    out.sort(key=lambda a: a["icao"])
    doc = {
        "source": "OurAirports (ourairports.com), public domain; generated by tools/make_airports.py",
        "airports": out,
    }
    with open(dst, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"{len(out)} airports -> {dst}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
